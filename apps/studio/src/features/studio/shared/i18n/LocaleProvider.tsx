const LocaleContext = createContext<Locale>('en')

export function translateMessage(
  locale: Locale,
  key: string,
  values?: Record<string, number | string>,
) {
  const message =
    (locale === 'vi' ? additionalVietnamese[key] : undefined) ||
    messages[locale][key] ||
    messages.en[key] ||
    key
  return values
    ? message.replace(/\{(\w+)\}/g, (match, name: string) =>
        values[name] === undefined ? match : String(values[name]),
      )
    : message
}

export function LocaleProvider({
  locale: initialLocale,
  children,
}: {
  locale: Locale
  children: ReactNode
}) {
  const [locale, setLocale] = useState<Locale>(initialLocale)
  useEffect(() => {
    let active = true
    void getRecord('settings', 'current')
      .then((settings) => {
        if (!active) return
        const savedLocale = settings?.locale
        if (savedLocale === 'en' || savedLocale === 'vi') {
          setLocale(savedLocale)
          document.documentElement.lang = savedLocale
        }
      })
      .catch(() => undefined)
    return () => {
      active = false
    }
  }, [])
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const locale = useContext(LocaleContext)
  const t = useCallback(
    (key: string, values?: Record<string, number | string>) =>
      translateMessage(locale, key, values),
    [locale],
  )
  return {
    locale,
    t,
  }
}

export function formatLocaleNumber(value: number, locale: Locale) {
  return new Intl.NumberFormat(locale === 'vi' ? 'vi-VN' : 'en-US').format(value)
}

export function formatLocaleDate(value: string | Date | null | undefined, locale: Locale) {
  if (!value) return '—'
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return '—'
  return new Intl.DateTimeFormat(locale === 'vi' ? 'vi-VN' : 'en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date)
}

export function formatLocaleBytes(value: number, locale: Locale) {
  if (!Number.isFinite(value) || value <= 0) return '0 B'
  const units = ['B', 'KB', 'MB', 'GB', 'TB']
  const index = Math.min(units.length - 1, Math.floor(Math.log(value) / Math.log(1024)))
  const number = new Intl.NumberFormat(locale === 'vi' ? 'vi-VN' : 'en-US', {
    maximumFractionDigits: index ? 1 : 0,
  }).format(value / 1024 ** index)
  return `${number} ${units[index]}`
}
