const workflowPaletteNodeTypes = new Set([
  'input.prompt',
  'input.image',
  'processing.template',
  'ai.generate-text',
  'ai.analyze-image',
  'ai.generate-image',
  'ai.edit-image',
  'ai.generate-video',
  'ai.image-to-video',
  'output.preview',
])

export const paletteNodeRegistry = nodeRegistry.filter((definition) =>
  workflowPaletteNodeTypes.has(definition.type),
)

export const registryByType = new Map(
  nodeRegistry.map((definition) => [definition.type, definition]),
)

export function canConnect(
  sourceType: string,
  sourceHandle: string,
  targetType: string,
  targetHandle: string,
) {
  const source = registryByType.get(sourceType)?.outputs.find((port) => port.id === sourceHandle)
  const target = registryByType.get(targetType)?.inputs.find((port) => port.id === targetHandle)
  return Boolean(source && target && source.dataType === target.dataType)
}
